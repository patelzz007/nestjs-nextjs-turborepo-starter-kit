// `pnpm --filter @workspace/admin gallery:examples` builds
// components/component-gallery/examples/examples-registry.tsx from the
// example folders: every `examples/<component>/index.tsx` that exports a
// `<Pascal>Examples` component becomes one `next/dynamic` chunk keyed by the
// gallery section id `component-<component>`. It also writes
// examples-manifest.ts, each component's example count: plain data with no
// client code, so the server-rendered overview can show the counts without
// loading a single example. Dependency-free (node built-ins only), so `node`
// runs it directly; the gallery test checks the committed files match what
// this produces.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

/** Where the example folders live, relative to apps/admin. */
export const EXAMPLES_DIR = "components/component-gallery/examples";

const SECTION_ID_PREFIX = "component-";

/** `data-grid` → `DataGrid`. */
export function pascalCaseOf(kebab: string): string {
	return kebab
		.split("-")
		.map((part: string): string => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
		.join("");
}

/** The component folders with an index that exports their `<Pascal>Examples`, sorted. */
export function exampleFolders(adminRoot: string): string[] {
	const dir = path.join(adminRoot, EXAMPLES_DIR);
	return readdirSync(dir, { withFileTypes: true })
		.filter((entry) => entry.isDirectory() && entry.name !== "__tests__")
		.map((entry) => entry.name)
		.filter((name: string): boolean => {
			const index = path.join(dir, name, "index.tsx");
			return existsSync(index) && readFileSync(index, "utf8").includes(`export function ${pascalCaseOf(name)}Examples(`);
		})
		.sort();
}

/** One example row of an examples index (`\t{ id: "c-kbd-1", label: …, component: … },`). */
const EXAMPLE_ROW = /^\t\{ id: "c-[a-z0-9-]+",/gmu;

/** How many examples `examples/<folder>/index.tsx` lists. */
export function exampleCount(adminRoot: string, folder: string): number {
	return readFileSync(path.join(adminRoot, EXAMPLES_DIR, folder, "index.tsx"), "utf8").match(EXAMPLE_ROW)?.length ?? 0;
}

/** One component's example count, keyed by its gallery section id. */
export interface ExampleCount {
	readonly folder: string;
	readonly count: number;
}

/** The manifest module's source: each component's example count. */
export function manifestSource(counts: readonly ExampleCount[]): string {
	const entries = counts.map(({ folder, count }: ExampleCount): string => `\t["${SECTION_ID_PREFIX}${folder}", ${String(count)}],`);
	return `// GENERATED by \`pnpm --filter @workspace/admin gallery:examples\` — do not edit by hand.
// How many worked examples each component has (examples/<component>/index.tsx),
// keyed by its gallery section id. Plain data, safe to import on the server.

export const GALLERY_EXAMPLE_COUNTS: ReadonlyMap<string, number> = new Map<string, number>([
${entries.join("\n")}
]);
`;
}

/** The registry module's source for `folders`. */
export function registrySource(folders: readonly string[]): string {
	const imports = folders.map((name: string): string => {
		const component = `${pascalCaseOf(name)}Examples`;
		return `const ${component} = dynamic(() => import("@/components/component-gallery/examples/${name}").then((m) => m.${component}), { loading: ExamplesLoading });`;
	});
	const entries = folders.map((name: string): string => `\t["${SECTION_ID_PREFIX}${name}", (): React.JSX.Element => <${pascalCaseOf(name)}Examples />],`);
	return `"use client";

// GENERATED by \`pnpm --filter @workspace/admin gallery:examples\` — do not edit by hand.
// Every component's worked examples (examples/<component>/index.tsx), keyed by
// its gallery section id. Each is its own chunk (\`next/dynamic\`), downloaded
// only when that section's examples scroll into view.

import dynamic from "next/dynamic";
import type * as React from "react";

import { ExamplesLoading } from "@/components/component-gallery/examples/examples-loading";

${imports.join("\n")}

/** Renders one section's examples (a render function, not a component: picking a component during render would remount it). */
export type RenderGalleryExamples = () => React.JSX.Element;

export const GALLERY_EXAMPLE_SECTIONS: ReadonlyMap<string, RenderGalleryExamples> = new Map<string, RenderGalleryExamples>([
${entries.join("\n")}
]);
`;
}

// Run directly (`node scripts/gallery-examples-registry.ts`): rewrite the registry.
if (import.meta.main) {
	const adminRoot = path.resolve(import.meta.dirname, "..");
	const folders = exampleFolders(adminRoot);
	writeFileSync(path.join(adminRoot, EXAMPLES_DIR, "examples-registry.tsx"), registrySource(folders));
	const counts = folders.map((folder: string): ExampleCount => ({ folder, count: exampleCount(adminRoot, folder) }));
	writeFileSync(path.join(adminRoot, EXAMPLES_DIR, "examples-manifest.ts"), manifestSource(counts));
	const total = counts.reduce((sum: number, { count }: ExampleCount): number => sum + count, 0);
	process.stdout.write(`examples registry: ${String(folders.length)} components, ${String(total)} examples\n`);
}
