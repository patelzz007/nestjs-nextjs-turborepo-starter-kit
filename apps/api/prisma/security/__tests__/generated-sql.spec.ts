import { readFileSync } from "node:fs";
import { resolve } from "node:path";

import { describe, expect, expectTypeOf, it } from "vitest";

import { SYSTEM_OPERATIONS } from "../../../src/prisma/system-operation.registry";
import { findStaleGeneratedFiles } from "../generated-files";
import { allFunctions, GENERATED_SQL_PATHS, renderFunctions, renderGrants, renderRoles, renderSecurityFiles, renderTriggers, sqlName } from "../generator";
import { PolicyDeclarationError } from "../generator/policy-clauses";
import { FUNCTION_SIGNATURES, type FunctionSignature } from "../generator/security-function";
import { parsePrismaSchemaModels } from "../manifest-index";
import { DATABASE_ROLES, type DatabaseRole, type DatabaseRoleName, type TableGrant } from "../roles";
import type { ScopedOperations } from "../system-operation-scopes";
import type { TableName } from "../table-types";
import type { SecurityTrigger } from "../triggers";

const apiDir = resolve(import.meta.dirname, "..", "..", "..");
const knownTables: ReadonlySet<string> = new Set(parsePrismaSchemaModels(readFileSync(resolve(apiDir, "prisma", "schema.prisma"), "utf8")).map((model) => model.tableName));
const OPERATIONS: ScopedOperations = { "outbox.publish": { scope: { kind: "tables", tables: ["OutboxEvent"] } } };

function committed(path: string): string {
	return readFileSync(resolve(apiDir, path), "utf8");
}

describe("the generated security SQL (prisma/rls)", () => {
	it("matches what prisma/security generates — run `pnpm --filter @workspace/api db:generate-security` and commit", () => {
		const rendered = renderSecurityFiles({ operations: SYSTEM_OPERATIONS, knownTables });
		expect(rendered.map((file) => file.path)).toStrictEqual(GENERATED_SQL_PATHS);
		for (const file of rendered) {
			expect(committed(file.path), file.path).toBe(file.sql);
		}
	});

	it("calls the scoped bypass only as `(SELECT app_rls_bypass_on(…))`: once per query, never once per row (it is PL/pgSQL)", () => {
		const policies = committed("prisma/rls/04-policies.sql");
		const calls = policies.match(/app_rls_bypass_on\(/gu) ?? [];
		const wrapped = policies.match(/\(SELECT app_rls_bypass_on\('[A-Za-z]+'\)\)/gu) ?? [];

		expect(calls.length).toBeGreaterThan(0);
		expect(wrapped).toHaveLength(calls.length);
	});

	it("is deterministic: the same input renders byte for byte the same files", () => {
		expect(renderSecurityFiles({ operations: SYSTEM_OPERATIONS, knownTables })).toStrictEqual(renderSecurityFiles({ operations: SYSTEM_OPERATIONS, knownTables }));
	});

	it("marks every file as generated, naming the command that regenerates it", () => {
		for (const path of GENERATED_SQL_PATHS) {
			expect(committed(path)).toContain(`-- ${path} — GENERATED by prisma/security; do not edit.`);
			expect(committed(path)).toContain("pnpm --filter @workspace/api db:generate-security");
		}
	});
});

describe("findStaleGeneratedFiles", () => {
	it("names a file whose committed text differs, or that is missing", () => {
		const files = [
			{ path: "a.sql", sql: "A" },
			{ path: "b.sql", sql: "B" },
			{ path: "c.sql", sql: "C" },
		];
		const disk = new Map([
			["a.sql", "A"],
			["b.sql", "old"],
		]);
		expect(findStaleGeneratedFiles(files, (path) => disk.get(path))).toStrictEqual(["b.sql", "c.sql"]);
	});
});

describe("renderRoles", () => {
	it("creates each role only if missing, and lets the applying login SET ROLE to the ones that need it", () => {
		const sql = renderRoles(DATABASE_ROLES);
		expect(sql).toContain("IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_runtime') THEN\n    CREATE ROLE app_runtime NOLOGIN NOSUPERUSER NOINHERIT NOBYPASSRLS;");
		expect(sql).toContain("GRANT app_runtime TO CURRENT_USER;");
		expect(sql).toContain("GRANT analytics_consumer TO CURRENT_USER;");
		expect(sql).not.toContain("GRANT app_backup TO CURRENT_USER;");
		const creates = sql.split("\n").filter((line) => line.trim().startsWith("CREATE ROLE"));
		expect(creates).toHaveLength(Object.keys(DATABASE_ROLES).length);
		for (const line of creates) {
			expect(line).toMatch(/ NOLOGIN .* NOBYPASSRLS;$/u);
		}
	});
});

describe("renderFunctions", () => {
	it("defines the primitives first, then the registry's scoped bypass, then everything that calls them", () => {
		const names = allFunctions(OPERATIONS, new Set(["OutboxEvent"])).map((fn) => fn.name);
		expect(names.indexOf("app_current_user_id")).toBeLessThan(names.indexOf("app_rls_bypass_on"));
		expect(names.indexOf("app_rls_bypass_on")).toBeLessThan(names.indexOf("app_member_of"));
		expect(names.indexOf("app_api_key_org_access")).toBeLessThan(names.indexOf("app_api_key_customer_access"));
	});

	it("hands a SECURITY DEFINER function to its owner role", () => {
		const sql = renderFunctions(allFunctions(OPERATIONS, new Set(["OutboxEvent"])));
		expect(sql).toContain("ALTER FUNCTION public.app_purge_audit_batch(text, bigint, integer, boolean) OWNER TO app_retention;");
		expect(sql).toContain("ALTER FUNCTION public.app_mask_erased_person(text, text) OWNER TO app_erasure;");
	});
});

describe("the role and trigger declaration types", () => {
	it("accepts only real tables, and a column grant only that table's columns", () => {
		expectTypeOf<{ tables: ["AnalyticsEvent"]; privileges: ["SELECT"]; columns: ["id"] }>().toExtend<TableGrant>();
		expectTypeOf<{ tables: ["AnalyticsEvent"]; privileges: ["SELECT"]; columns: ["notAColumn"] }>().not.toExtend<TableGrant>();
		expectTypeOf<{ tables: ["NotATable"]; privileges: ["SELECT"] }>().not.toExtend<TableGrant>();
		expectTypeOf<SecurityTrigger["table"]>().toEqualTypeOf<TableName>();
	});
});

describe("renderTriggers", () => {
	it("drops and re-creates each trigger, and refuses one on an unknown table", () => {
		const trigger: SecurityTrigger = {
			name: "t",
			table: "User",
			purpose: "p",
			definition: 'CREATE TRIGGER t AFTER INSERT ON public."User" FOR EACH ROW EXECUTE FUNCTION f();',
		};
		expect(renderTriggers([trigger], new Set(["User"]))).toContain(`DROP TRIGGER IF EXISTS t ON public."User";\nCREATE TRIGGER t`);
		expect((): string => renderTriggers([trigger], new Set())).toThrow(PolicyDeclarationError);
	});
});

describe("renderGrants", () => {
	const functions = allFunctions(OPERATIONS, new Set(["OutboxEvent"]));

	it("resets a narrow role before granting it exactly its tables and functions", () => {
		const sql = renderGrants(DATABASE_ROLES, functions, knownTables);
		expect(sql).toContain(
			[
				"REVOKE ALL ON ALL TABLES IN SCHEMA public FROM app_enumerator;",
				"REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM app_enumerator;",
				"GRANT USAGE ON SCHEMA public TO app_enumerator;",
				'GRANT SELECT ON TABLE public."Tenant" TO app_enumerator;',
			].join("\n"),
		);
		expect(sql).toContain('GRANT SELECT (id) ON TABLE public."AnalyticsEvent" TO analytics_consumer;');
		expect(sql).toContain("REVOKE ALL ON FUNCTION public.app_purge_audit_batch(text, bigint, integer, boolean) FROM PUBLIC;");
		expect(sql).toContain("GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO app_runtime;");
		expect(sql).toContain("ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO app_backup;");
	});

	it("refuses a grant on an unknown table or of an undefined function", () => {
		const unknownTable: Record<DatabaseRoleName, DatabaseRole> = {
			...DATABASE_ROLES,
			app_enumerator: { ...DATABASE_ROLES.app_enumerator, tableGrants: [{ tables: ["BackupCode"], privileges: ["SELECT"] }] },
		};
		const withoutBackupCode = new Set([...knownTables].filter((table: string): boolean => table !== "BackupCode"));
		expect((): string => renderGrants(unknownTable, functions, withoutBackupCode)).toThrow(/does not have: BackupCode/);
		const withoutMemberOf = functions.filter((fn) => fn.signature !== "app_member_of(text)");
		expect((): string => renderGrants(DATABASE_ROLES, withoutMemberOf, knownTables)).toThrow(/does not define: app_member_of\(text\)/);
	});
});

describe("the function signatures", () => {
	it("are each defined exactly once, and nothing is defined without one", () => {
		const defined = allFunctions(SYSTEM_OPERATIONS, knownTables).map((fn) => fn.signature);
		expect(new Set(defined).size).toBe(defined.length);
		expect([...defined].sort()).toStrictEqual([...FUNCTION_SIGNATURES].sort());
	});

	it("are what roles.ts may grant (a typo does not compile)", () => {
		expectTypeOf<NonNullable<DatabaseRole["executes"]>[number]>().toEqualTypeOf<FunctionSignature>();
		expectTypeOf<"app_gone(text)">().not.toExtend<FunctionSignature>();
	});
});

describe("sqlName", () => {
	it("leaves a lower-case name bare, quotes a mixed-case one, and rejects anything else", () => {
		expect(sqlName("users_own")).toBe("users_own");
		expect(sqlName("TenantPlacement_member")).toBe('"TenantPlacement_member"');
		expect((): string => sqlName('x"; DROP TABLE y; --')).toThrow(PolicyDeclarationError);
	});
});
