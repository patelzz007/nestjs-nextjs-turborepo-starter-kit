// ============================================
// infrastructure/load-test/load-test-reward-image.ts — the picture every provisioned reward shows
// ============================================
// A published reward always shows at least one READY image, so the Load Test tenant's rewards need
// a real one. It is drawn here, in memory (no bundled asset): a plain slate-grey PNG at the smallest
// size the REWARD_IMAGE pixel rules accept, labelled as a load-test picture in its EXIF and its file
// name. The files context stores it like any upload — checks, scan, renditions (`ServerFileIngest`)
// — and, the bytes being the same every time, hands back the same file on every later run.
//
// Design patterns:
//   - ADAPTER for `LoadTestRewardImagePort` over the files context's published ingest.

import { getFileCategoryPolicy, ImageRulesSchema } from "@workspace/shared";
import sharp, { type Create } from "sharp";

import type { ActorContext } from "../../../../platform/application/actor-context";
import type { ServerFileIngest } from "../../../files/public-api";
import type { LoadTestRewardImagePort } from "../../application/ports/load-test.ports";

/** The stored file's name: says what it is wherever the file is listed. */
export const LOAD_TEST_REWARD_IMAGE_NAME = "load-test-reward.png";
/** The EXIF description the picture carries. */
export const LOAD_TEST_REWARD_IMAGE_LABEL = "Load test reward picture: generated by the load-test provisioner, not a real reward photo";
/** Slate grey (`#64748b`): plainly not a photo. */
const PICTURE_BACKGROUND = { r: 100, g: 116, b: 139 } satisfies Create["background"];
const RGB_CHANNELS = 3;

/** The picture's bytes: deterministic, so an ingest of an earlier run's picture finds it. */
export async function renderLoadTestRewardPicture(): Promise<Buffer> {
	const { minWidth, minHeight } = ImageRulesSchema.parse(getFileCategoryPolicy("REWARD_IMAGE").imageRules);
	return sharp({ create: { width: minWidth, height: minHeight, channels: RGB_CHANNELS, background: PICTURE_BACKGROUND } })
		.withExif({ IFD0: { ImageDescription: LOAD_TEST_REWARD_IMAGE_LABEL } })
		.png()
		.toBuffer();
}

export class LoadTestRewardImage implements LoadTestRewardImagePort {
	public constructor(private readonly files: Pick<ServerFileIngest, "ingest">) {}

	public async ensure(actor: ActorContext, tenantId: string, uploadedById: string): Promise<string> {
		return this.files.ingest(actor, {
			upload: { category: "REWARD_IMAGE", tenantId, fileName: LOAD_TEST_REWARD_IMAGE_NAME, mimeType: "image/png" },
			uploadedById,
			bytes: await renderLoadTestRewardPicture(),
		});
	}
}
