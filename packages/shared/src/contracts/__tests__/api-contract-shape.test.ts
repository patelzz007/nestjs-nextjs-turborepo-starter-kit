/** Marks a contract leaf (`defineContract` / `defineFileContract`). */
const ContractLeafMarkerSchema = z.object({
	method: z.enum(["GET", "POST", "PUT", "PATCH", "DELETE"]),
	path: z.string().min(1),
});

const ContractBranchSchema = z.record(z.string(), z.instanceof(Object));

function collectContractLines(node: z.output<typeof ContractBranchSchema>, prefix: string): string[] {
	const lines: string[] = [];
	for (const [key, value] of Object.entries(node)) {
		const leaf = ContractLeafMarkerSchema.safeParse(value);
		if (leaf.success) {
			lines.push(`${prefix}${key} ${leaf.data.method} ${leaf.data.path}`);
		} else {
			lines.push(...collectContractLines(ContractBranchSchema.parse(value), `${prefix}${key}.`));
		}
	}
	return lines;
}

function collectRouteLines(node: RouteTree, prefix: string): string[] {
	if (isStringPrimitive(node)) {
		return [`${prefix} ${node}`];
	}
	return Object.entries(node).flatMap(([key, child]) => {
		const dotted = prefix.length > 0 ? `${prefix}.${key}` : key;
		return collectRouteLines(child, dotted);
	});
}

function sortedSharedExportNames(): string[] {
	return Object.keys(sharedPackage).sort((left, right) => left.localeCompare(right));
}

