#!/usr/bin/env node
/**
 * Generate locally-owned API secrets using `openssl rand -base64 128`.
 * External credentials (RESEND_API_KEY, RESEND_WEBHOOK_SECRET) are not generated here.
 */
import { execSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();

/** App-owned secrets — each value is `openssl rand -base64 128`. */
const APP_SECRET_KEYS = [
	"JWT_ACCESS_SECRET",
	"JWT_REFRESH_SECRET",
	"EMAIL_VERIFICATION_SECRET",
	"TWO_FACTOR_PENDING_SECRET",
];

function generateSecretBase64() {
	try {
		// OpenSSL wraps long base64 across multiple lines — collapse to a single line for .env files.
		return execSync("openssl rand -base64 128", { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).replace(/\s+/g, "");
	} catch {
		return randomBytes(128).toString("base64");
	}
}

function generateSecrets() {
	const secrets = {};
	for (const key of APP_SECRET_KEYS) {
		secrets[key] = generateSecretBase64();
	}
	secrets.MFA_ENCRYPTION_KEYS = JSON.stringify({ 1: generateSecretBase64() });
	return secrets;
}

function formatEnvBlock(secrets) {
	return [
		"# --- Generated by: pnpm secrets:generate (openssl rand -base64 128) ---",
		`JWT_ACCESS_SECRET=${secrets.JWT_ACCESS_SECRET}`,
		`JWT_REFRESH_SECRET=${secrets.JWT_REFRESH_SECRET}`,
		`EMAIL_VERIFICATION_SECRET=${secrets.EMAIL_VERIFICATION_SECRET}`,
		`TWO_FACTOR_PENDING_SECRET=${secrets.TWO_FACTOR_PENDING_SECRET}`,
		`MFA_ENCRYPTION_KEYS='${secrets.MFA_ENCRYPTION_KEYS}'`,
	].join("\n");
}

function upsertEnvFile(envPath, secrets) {
	const absolutePath = path.isAbsolute(envPath) ? envPath : path.join(ROOT, envPath);
	const original = readFileSync(absolutePath, "utf8");
	const lines = original.split("\n");
	const keysToSet = new Set([...APP_SECRET_KEYS, "MFA_ENCRYPTION_KEYS"]);

	const nextLines = [];
	const replaced = new Set();

	for (let index = 0; index < lines.length; index += 1) {
		const line = lines[index];
		const match = /^([A-Za-z_][A-Za-z0-9_]*)\s*=/.exec(line);
		if (match !== null && keysToSet.has(match[1])) {
			const key = match[1];
			if (key === "MFA_ENCRYPTION_KEYS") {
				nextLines.push(`MFA_ENCRYPTION_KEYS='${secrets.MFA_ENCRYPTION_KEYS}'`);
			} else {
				nextLines.push(`${key}=${secrets[key]}`);
			}
			replaced.add(key);

			// Drop orphaned continuation lines from previously wrapped openssl output.
			let cursor = index + 1;
			while (cursor < lines.length) {
				const continuation = lines[cursor];
				if (continuation.trim().length === 0 || continuation.trim().startsWith("#") || /^[A-Za-z_][A-Za-z0-9_]*\s*=/.test(continuation)) {
					break;
				}
				cursor += 1;
			}
			index = cursor - 1;
			continue;
		}
		nextLines.push(line);
	}

	for (const key of keysToSet) {
		if (!replaced.has(key)) {
			if (key === "MFA_ENCRYPTION_KEYS") {
				nextLines.push(`MFA_ENCRYPTION_KEYS='${secrets.MFA_ENCRYPTION_KEYS}'`);
			} else {
				nextLines.push(`${key}=${secrets[key]}`);
			}
		}
	}

	writeFileSync(absolutePath, `${nextLines.join("\n").replace(/\n*$/, "")}\n`, "utf8");
}

function main() {
	const writeTarget = process.argv[2];
	const secrets = generateSecrets();

	if (writeTarget === undefined) {
		console.log(formatEnvBlock(secrets));
		console.log("\n# Paste into apps/api/.env, or run: pnpm secrets:generate apps/api/.env");
		return;
	}

	upsertEnvFile(writeTarget, secrets);
	console.log(`Updated secrets in ${writeTarget} (openssl rand -base64 128).`);
	console.log("Rotating JWT/MFA secrets invalidates existing sessions — users must sign in again.");
}

main();
