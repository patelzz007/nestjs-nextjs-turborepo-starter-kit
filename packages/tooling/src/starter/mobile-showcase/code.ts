// Every example's source, coloured at generate time so the phone never runs a
// highlighter. Shiki reads each source with the web's own theme (GitHub
// light, the one the web's code blocks draw), and each colour is named by
// what it marks (its role): the phone draws a role with its own theme token
// (`text-code-<role>`), so light and dark follow the app's theme and no
// colour literal reaches the app. GitHub dark gives every role its dark
// colour, so naming the light colour is enough.
//
// Output: generated/code/<component>.ts (every example's lines of
// `[role, text]` tokens, by file) and generated/code/index.ts (each behind a
// dynamic import, loaded when a code view first opens).
//
// Code an example shows *inside* a code block (a CodeBlock example's snippet) is
// coloured the same way, in its own language: a component's `snippets.json`
// ({ id, language, code }) becomes generated/snippets/<component>.ts.

import { existsSync, readFileSync } from "node:fs";
import path from "node:path";

import { createHighlighter, type BundledLanguage, type BundledTheme, type HighlighterGeneric, type ThemedToken } from "shiki";
import { z } from "zod";

import type { ComponentFeatures, ExampleFile } from "./features.ts";
import { examplesOf } from "./features.ts";

/** The roles, in the order of the app's `CodeRoleSchema` (features/showcase/showcase-code.ts): a token stores its role's position. */
export const CODE_ROLES: readonly string[] = ["plain", "keyword", "function", "constant", "string", "comment", "tag", "parameter"];

/** GitHub light's colours, by the role each marks. */
export const GITHUB_LIGHT_ROLES: ReadonlyMap<string, string> = new Map<string, string>([
	["#24292E", "plain"],
	["#D73A49", "keyword"],
	["#6F42C1", "function"],
	["#005CC5", "constant"],
	["#032F62", "string"],
	["#6A737D", "comment"],
	["#22863A", "tag"],
	["#E36209", "parameter"],
]);

const THEME = "github-light";
const LANGUAGE = "tsx";
/** The languages a snippet may be written in. */
export const SNIPPET_LANGUAGES: readonly ["tsx", "typescript", "python", "sql", "bash"] = ["tsx", "typescript", "python", "sql", "bash"];

/** One token: its role's position in `CODE_ROLES`, and its text. */
export type CodeToken = readonly [number, string];
export type HighlightedLines = readonly (readonly CodeToken[])[];

/** Between two tokens of a line (the app's `TOKEN_SEPARATOR`, features/showcase/showcase-code.ts). */
export const TOKEN_SEPARATOR = "\u001f";

/** Lines of tokens in the app's compact form: lines joined by "\n", tokens by `TOKEN_SEPARATOR`, each a role digit then its text. */
export function encodeHighlighted(lines: HighlightedLines, file: string): string {
	return lines
		.map((line: readonly CodeToken[]): string =>
			line
				.map(([role, text]: CodeToken): string => {
					if (text.includes(TOKEN_SEPARATOR)) {
						throw new Error(`${file}: the source holds the unit separator (U+001F), which the code colouring uses between tokens`);
					}
					return `${String(role)}${text}`;
				})
				.join(TOKEN_SEPARATOR),
		)
		.join("\n");
}

type Highlighter = HighlighterGeneric<BundledLanguage, BundledTheme>;

/** Shiki, loaded once with the one theme and language the examples need. */
export function loadHighlighter(): Promise<Highlighter> {
	const [tsx, typescript, python, sql, bash] = SNIPPET_LANGUAGES;
	return createHighlighter({ themes: [THEME], langs: [tsx, typescript, python, sql, bash] });
}

/** The role position of a GitHub light colour; an unknown colour fails the build, so a theme change is noticed. */
export function rolePositionOf(color: string | undefined, file: string): number {
	const role = GITHUB_LIGHT_ROLES.get((color ?? "").toUpperCase());
	const position = role === undefined ? -1 : CODE_ROLES.indexOf(role);
	if (position < 0) {
		throw new Error(`${file}: Shiki coloured a token ${String(color)}, which no code role names (add it to GITHUB_LIGHT_ROLES)`);
	}
	return position;
}

/** `source` as lines of tokens, neighbours of one role merged. */
export function highlightSource(highlighter: Highlighter, source: string, file: string, language: BundledLanguage = LANGUAGE): HighlightedLines {
	return highlighter.codeToTokensBase(source.replace(/\n$/u, ""), { lang: language, theme: THEME }).map((line: ThemedToken[]): CodeToken[] => {
		const merged: CodeToken[] = [];
		for (const token of line) {
			const role = rolePositionOf(token.color, file);
			const [lastRole, lastText = ""] = merged.at(-1) ?? [];
			if (lastRole === role) {
				merged.splice(-1, 1, [role, `${lastText}${token.content}`]);
			} else {
				merged.push([role, token.content]);
			}
		}
		return merged;
	});
}

const GENERATED_HEADER = "// GENERATED by the showcase generator — do not edit by hand.";

/** One component's code module: every example's coloured lines, by file name. */
export function codeModuleSource(highlighter: Highlighter, component: ComponentFeatures): string {
	const rows = examplesOf(component).map(
		(example: ExampleFile): string =>
			`\t[${JSON.stringify(example.file)}, ${JSON.stringify(encodeHighlighted(highlightSource(highlighter, example.source, `${component.slug}/${example.file}`), `${component.slug}/${example.file}`))}],`,
	);
	return `${GENERATED_HEADER}
// The ${component.slug} component's examples, coloured (the compact form of features/showcase/showcase-code.ts).

import type { HighlightedCode } from "../../showcase-code";

export const SHOWCASE_COMPONENT_CODE: ReadonlyMap<string, HighlightedCode> = new Map<string, HighlightedCode>([
${rows.join("\n")}
]);
`;
}

/** The index: every component's code module behind a dynamic import. */
export function codeIndexSource(slugs: readonly string[]): string {
	const rows = slugs.map(
		(slug: string): string => `\t[${JSON.stringify(slug)}, async (): Promise<ReadonlyMap<string, HighlightedCode>> => (await import("./${slug}")).SHOWCASE_COMPONENT_CODE],`,
	);
	return `${GENERATED_HEADER}
// Every component's coloured examples, each loaded when one of its code views first opens.

import type { HighlightedCode } from "../../showcase-code";

export type LoadShowcaseCode = () => Promise<ReadonlyMap<string, HighlightedCode>>;

export const SHOWCASE_CODE: ReadonlyMap<string, LoadShowcaseCode> = new Map<string, LoadShowcaseCode>([
${rows.join("\n")}
]);
`;
}

/** One snippet an example shows in a code block: its id, its language and its code. */
export const SnippetSchema = z
	.object({
		id: z.string().min(1),
		language: z.enum(SNIPPET_LANGUAGES),
		code: z.string(),
	})
	.strict();

export type Snippet = z.output<typeof SnippetSchema>;

/** A component's `snippets.json`, or none when the folder has no such file. */
export function readSnippets(examplesDir: string, slug: string): readonly Snippet[] {
	const file = path.join(examplesDir, slug, "snippets.json");
	if (!existsSync(file)) {
		return [];
	}
	const parsed = z.array(SnippetSchema).safeParse(JSON.parse(readFileSync(file, "utf8")));
	if (!parsed.success) {
		throw new Error(`${slug}/snippets.json: ${parsed.error.message}`);
	}
	return parsed.data;
}

/** One component's snippets module: each snippet's code and its coloured lines, by id. */
export function snippetModuleSource(highlighter: Highlighter, slug: string, snippets: readonly Snippet[]): string {
	const rows = snippets.map(
		(snippet: Snippet): string =>
			`\t[${JSON.stringify(snippet.id)}, { code: ${JSON.stringify(snippet.code)}, lines: ${JSON.stringify(encodeHighlighted(highlightSource(highlighter, snippet.code, `${slug}/snippets.json#${snippet.id}`, snippet.language), `${slug}/snippets.json#${snippet.id}`))} }],`,
	);
	return `${GENERATED_HEADER}
// The ${slug} examples' snippets, coloured at generate time (the compact form of features/showcase/showcase-code.ts).

import type { HighlightedCode } from "../../showcase-code";

export const SHOWCASE_SNIPPETS: ReadonlyMap<string, { readonly code: string; readonly lines: HighlightedCode }> = new Map<string, { readonly code: string; readonly lines: HighlightedCode }>([
${rows.join("\n")}
]);
`;
}
