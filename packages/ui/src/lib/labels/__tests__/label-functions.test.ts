/** The cascader's search label is a string, or a function of the parent's label: both shapes are allowed. */
function cascaderSearch(pack: UiKitLabels): readonly string[] {
	const { search } = pack.cascader;
	return search instanceof Function ? [search(undefined), search("Fruit")] : [search];
}

