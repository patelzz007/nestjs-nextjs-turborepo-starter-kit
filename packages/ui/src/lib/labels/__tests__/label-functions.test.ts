describe("every label function of every pack", () => {
	it.each(UI_KIT_LANGUAGES)("%s produces non-empty text for every call", (language) => {
		const produced = exercise(UI_KIT_LANGUAGE_PACKS[language]);
		expect(produced.length).toBeGreaterThan(200);
		expect(produced.filter((text) => text.trim().length === 0)).toStrictEqual([]);
	});

	it.each(UI_KIT_LANGUAGES.filter((language) => language !== "en"))("%s says something different from English for most calls", (language) => {
		const english = exercise(UI_KIT_LANGUAGE_PACKS.en);
		const translated = exercise(UI_KIT_LANGUAGE_PACKS[language]);
		const same = translated.filter((text, index) => text === english[index]);
		expect(same.length / translated.length).toBeLessThan(0.35);
	});
});
