/** The cascader's root-level name — also the start of its root announcement. */
const CASCADER_ROOT_LEVEL_EN = "Top level";

function cascaderItemCountEn(count: number): string {
	return `${String(count)} ${count === 1 ? "item" : "items"}`;
}

/** "Deeper" is the direction the text runs, so the level keys mirror in RTL and the hint names the mirrored pair. */
function cascaderKeyboardHintEn(mode: CascaderMode, dir: CascaderDirection): string {
	const open = dir === "rtl" ? "Left" : "Right";
	const back = dir === "rtl" ? "Right" : "Left";
	if (mode === "tree") {
		return `Use the ${open} Arrow key to expand and the ${back} Arrow key to collapse.`;
	}
	if (mode === "columns") {
		return `Use the ${open} Arrow key to open the next column and the ${back} Arrow key to go back.`;
	}
	return `Use the ${open} Arrow key to open a branch and the ${back} Arrow key to go back.`;
}

